export const tarotDeck: readonly TarotCard[] = [
  ...major.map(([name, englishName, upright, reversed], index) => ({
    id: `major-${index.toString().padStart(2, '0')}`, name, englishName, arcana: 'major' as const, upright, reversed,
  })),
  ...suits.flatMap(({ id, name, englishName, cards }) => cards.map(([rank, englishRank, upright, reversed], index) => ({
    id: `${id}-${(index + 1).toString().padStart(2, '0')}`,
    name: `${name}${rank}`,
    englishName: `${englishRank} of ${englishName}`,
    arcana: 'minor' as const,
    suit: id,
    upright,
    reversed,
  }))),
]
